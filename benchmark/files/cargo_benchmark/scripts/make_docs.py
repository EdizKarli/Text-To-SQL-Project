#!/usr/bin/env python3
"""Generate docs/ERD.md (Mermaid ER diagram of the NORMAL schema) and docs/schema_variants.md
(every table and column in normal / mixed / cryptic form) from the built databases and schema/naming_map.json.
Usage: python scripts/make_docs.py"""
import json, os, sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    con = sqlite3.connect(os.path.join(ROOT, "databases", "cargo_normal.db"))
    naming = json.load(open(os.path.join(ROOT, "schema", "naming_map.json"), encoding="utf-8"))
    tables = [t for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY rowid")]

    rels, ents = [], []
    for t in tables:
        info = con.execute(f"PRAGMA table_info({t})").fetchall()
        fks = {r[3]: r[2] for r in con.execute(f"PRAGMA foreign_key_list({t})")}
        uniq = set()
        for _, iname, is_unique, *_ in con.execute(f"PRAGMA index_list({t})"):
            cols = [r[2] for r in con.execute(f"PRAGMA index_info({iname})")]
            if is_unique and len(cols) == 1:
                uniq.add(cols[0])
        attrs = []
        for _, name, typ, notnull, _, pk in info:
            key = ",".join(k for k, on in (("PK", pk), ("FK", name in fks), ("UK", name in uniq)) if on)
            attrs.append(f"        {(typ or 'TEXT').lower()} {name}{' ' + key if key else ''}")
        ents.append(f"    {t} {{\n" + "\n".join(attrs) + "\n    }")
        for col, parent in fks.items():
            nullable = not [r for r in info if r[1] == col][0][3]
            one = col in uniq
            card = ("|o--o|" if one else "|o--o{") if nullable else ("||--o|" if one else "||--o{")
            rels.append(f'    {parent} {card} {t} : "{col}"')
    with open(os.path.join(ROOT, "docs", "ERD.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Entity-Relationship Diagram (normal schema)\n\n"
                 "Generated by `scripts/make_docs.py` from `databases/cargo_normal.db`. Relationship labels name the foreign-key column. "
                 "The mixed and cryptic schemas have exactly the same structure with renamed identifiers "
                 "(see [schema_variants.md](schema_variants.md)).\n\n```mermaid\nerDiagram\n")
        fh.write("\n".join(rels) + "\n\n" + "\n".join(ents) + "\n```\n\n"
                 "`benchmark_meta(meta_key, meta_value)` is a stand-alone helper table holding the dataset's as-of timestamp "
                 "(`2025-12-20 00:00:00`), the generator seed and the schema version.\n")

    lines = ["# Schema variants: normal / mixed / cryptic", "",
             "Generated by `scripts/make_docs.py` from `schema/naming_map.json`. All three databases contain **identical rows**; "
             "only table, column and index names differ, so every question has the same Gold result in every variant.", "",
             "| Variant | Tables | Columns | Naming style | Files |", "|---|---|---|---|---|",
             "| normal | 20 | 300 | full English words (`shipments.declared_value_usd`) | `schema/schema.sql`, `databases/cargo_normal.db`, `questions/questions_normal.json` |",
             "| mixed | 20 | 300 | SAP-style abbreviations, mostly German mixed with English (`sndg.dekl_wert_usd`) | `schema/schema_mixed.sql`, `databases/cargo_mixed.db`, `questions/questions_mixed.json` |",
             "| cryptic | 20 | 300 | random table codes and positional columns (`t89v.c16`); comments stripped | `schema/schema_cryptic.sql`, `databases/cargo_cryptic.db`, `questions/questions_cryptic.json` |",
             "", "## Tables", "", "| normal | mixed | cryptic | columns |", "|---|---|---|---:|"]
    for t in tables:
        lines.append(f"| `{t}` | `{naming['mixed'][t]['name']}` | `{naming['cryptic'][t]['name']}` | {len(naming['normal'][t]['columns'])} |")
    lines += ["", "## Columns", ""]
    for t in tables:
        lines += [f"### {t} &nbsp;·&nbsp; {naming['mixed'][t]['name']} &nbsp;·&nbsp; {naming['cryptic'][t]['name']}", "",
                  "| normal | mixed | cryptic |", "|---|---|---|"]
        for c in naming["normal"][t]["columns"]:
            lines.append(f"| `{c}` | `{naming['mixed'][t]['columns'][c]}` | `{naming['cryptic'][t]['columns'][c]}` |")
        lines.append("")
    lines += ["## Glossary of mixed-schema abbreviations", "",
              "| abbreviation | meaning | | abbreviation | meaning |", "|---|---|---|---|---|"]
    gloss = [("abfl / ank", "Abflug / Ankunft = departure / arrival"), ("abschn", "Abschnitt = leg"),
             ("anm", "Anmeldung = declaration"), ("anz", "Anzahl = count"), ("bes", "Besatzung = crew"),
             ("bez", "Bezeichnung = name"), ("betankg", "Betankung = fuel uplift"), ("eins", "Einsatz = assignment"),
             ("eust", "Einfuhrumsatzsteuer = import VAT"), ("fh / flghf", "Flughafen = airport"),
             ("flges", "Fluggesellschaft = airline"), ("gefgut", "Gefahrgut = dangerous goods"), ("ges", "gesamt = total"),
             ("gew", "Gewicht = weight"), ("ist / plan", "actual / scheduled"), ("knd / kunnr", "Kunde / Kundennummer = customer"),
             ("kz", "Kennzeichen = flag (0/1)"), ("ladg", "Ladung = cargo / load"), ("lbf", "Luftfrachtbrief = air waybill"),
             ("lfz", "Luftfahrzeug = aircraft"), ("lgr", "Lager = warehouse"), ("rech", "Rechnung = invoice"),
             ("sndg / sdg", "Sendung = shipment"), ("stat", "Status"), ("vorf", "Vorfall = incident"),
             ("vers_schad", "Versicherungsschaden = insurance claim"), ("wartg", "Wartung = maintenance"),
             ("zahlg", "Zahlung = payment"), ("zoll", "Zoll = customs"), ("erdat", "Erstelldatum = created date")]
    half = (len(gloss) + 1) // 2
    for a, b in zip(gloss[:half], gloss[half:] + [("", "")]):
        lines.append(f"| `{a[0]}` | {a[1]} | | {('`' + b[0] + '`') if b[0] else ''} | {b[1]} |")
    with open(os.path.join(ROOT, "docs", "schema_variants.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote docs/ERD.md and docs/schema_variants.md")


if __name__ == "__main__":
    main()
