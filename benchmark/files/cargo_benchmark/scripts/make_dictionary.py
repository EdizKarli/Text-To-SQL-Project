#!/usr/bin/env python3
"""Write a readable data dictionary for one schema variant: docs/data_dictionary_<variant>.md

    python scripts/make_dictionary.py                    # cryptic (default)
    python scripts/make_dictionary.py --variant mixed

The meanings come from schema/descriptions.json (one entry per table and column, written for the normal names),
mapped to the variant's names with schema/naming_map.json. The same meanings are given to the model by
evaluation/run_ollama.py --dictionary (as comments in the schema).
"""
import argparse
import json
import os
import sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variant", choices=["normal", "mixed", "cryptic"], default="cryptic")
    a = ap.parse_args()
    desc = json.load(open(os.path.join(ROOT, "schema", "descriptions.json"), encoding="utf-8"))
    names = json.load(open(os.path.join(ROOT, "schema", "naming_map.json"), encoding="utf-8"))[a.variant]
    con = sqlite3.connect(os.path.join(ROOT, "databases", f"cargo_{a.variant}.db"))
    order = [t for (t,) in con.execute("SELECT name FROM sqlite_master WHERE type='table' ORDER BY rowid")]
    by_variant = {names[t]["name"]: t for t in desc}

    out = [f"# Data dictionary: {a.variant} schema", "",
           f"What every table and column of the {a.variant} schema means. Generated by `scripts/make_dictionary.py` "
           "from `schema/descriptions.json`; do not edit by hand.", "",
           "Give it to a model with `python evaluation/run_ollama.py --variant "
           f"{a.variant} --dictionary`. The model then sees each meaning as a comment in the schema.", "",
           "## Tables", "", "| Table | Meaning | Normal name |", "|---|---|---|"]
    for vt in order:
        t = by_variant[vt]
        out.append(f"| `{vt}` | {desc[t]['description']} | `{t}` |")
    for vt in order:
        t = by_variant[vt]
        cmap = names[t]["columns"]
        out += ["", f"## `{vt}`: {desc[t]['description']}", "", "| Column | Type | Meaning | Normal name |",
                "|---|---|---|---|"]
        for _, col, typ, _, _, pk in con.execute(f"PRAGMA table_info({vt})"):
            normal = next(c for c, v in cmap.items() if v == col)
            meaning = desc[t]["columns"][normal].replace("|", "/")
            out.append(f"| `{col}` | {typ}{' PK' if pk else ''} | {meaning} | `{normal}` |")
    path = os.path.join(ROOT, "docs", f"data_dictionary_{a.variant}.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"-> {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
