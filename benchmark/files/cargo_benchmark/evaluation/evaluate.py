#!/usr/bin/env python3
"""Score model-generated SQL against the Gold results, with accuracy and speed metrics.

Usage: python evaluation/evaluate.py predictions.json [--variant normal|mixed|cryptic] [--stats pred_x_raw.json]
                                     [--out results.json] [--timeout 30] [--only-predicted]
  predictions.json : {"E01-CAS": "SELECT ...", ...} (written by evaluation/run_ollama.py, or by any other system)
  --stats          : per-question model counters; defaults to <predictions>_raw.json next to the predictions
  --only-predicted : score only the questions present in the predictions file (for runs on a slice)

Metrics
  EX   execution accuracy        share of questions whose result matches the Gold result (relaxed matching, below)
  EX strict                      same, but rows in Gold order, columns in Gold order (only fair with --with-spec runs)
  VER  valid execution rate      share of questions whose SQL executed without error or timeout (right or wrong)
  latency                        model wall-clock seconds per question (mean, median, p95, total)
  tokens created                 tokens generated by the model (Ollama eval_count; mean and total)
  latency per token              wall-clock latency / tokens created, in ms per token (total / total)
  tokens per second              tokens created / generation time (Ollama eval_duration), i.e. pure decoding speed
  (the gap between latency/token and 1/(tokens per second) is prompt processing + model loading)

Relaxed matching (EX): same number of rows and columns; row order and column order are ignored; numbers match when
they agree to the precision the Gold result is shown with (half a unit of its last decimal; e.g. 62.2 matches
62.23 but not 62.3); text must match exactly. This is order-insensitive like BIRD's EX, plus rounding tolerance,
because the model is not shown the answer specification by default.

Outcomes per question: correct | wrong_result | execution_error | timeout | missing. SQL runs read-only with a timeout.
Matching on one dataset is evidence, not proof, of equivalence; validation/test_gold.py adds edge-case fixtures.
"""
import argparse, collections, itertools, json, math, os, sqlite3, statistics, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIFFS = ("easy", "moderate", "hard")
STYLES = ("casual", "schema_aware", "business_executive", "vague")


def run(db, sql, timeout):
    con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    start = time.time()
    con.set_progress_handler(lambda: 1 if time.time() - start > timeout else 0, 10000)
    try:
        cur = con.execute(sql.strip().rstrip(";").split(";")[0])
        rows = cur.fetchall()
        return "ok", rows, (time.time() - start) * 1000
    except sqlite3.OperationalError as e:
        return ("timeout" if "interrupted" in str(e) else "error"), str(e), (time.time() - start) * 1000
    except Exception as e:
        return "error", str(e), (time.time() - start) * 1000
    finally:
        con.close()


def is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def decimals(v):
    if isinstance(v, int):
        return 0
    s = repr(float(v))
    return 0 if "e" in s or "." not in s else min(6, len(s.split(".")[1].rstrip("0")))


def same_strict(a, b, tol=0.011):
    if len(a) != len(b):
        return False
    for ra, rb in zip(a, b):
        if len(ra) != len(rb):
            return False
        for x, y in zip(ra, rb):
            if is_num(x) and is_num(y):
                if abs(x - y) > tol:
                    return False
            elif x != y:
                return False
    return True


def same_relaxed(pred, gold):
    """Order-insensitive rows, column-permutation-insensitive, numbers to the Gold's displayed precision."""
    if len(pred) != len(gold):
        return False
    if not gold:
        return True
    ncol = len(gold[0])
    if any(len(r) != ncol for r in pred):
        return False
    prec = []
    for k in range(ncol):
        nums = [r[k] for r in gold if is_num(r[k])]
        d = max((decimals(v) for v in nums), default=0)
        prec.append(d)
    tol = [0.5 * 10 ** -d + 1e-9 for d in prec]

    def key(row):
        return tuple((0, round(v, prec[k])) if is_num(v) else (2, "") if v is None else (1, str(v)) for k, v in enumerate(row))

    def cell_eq(p, g, k):
        if is_num(p) and is_num(g):
            return abs(p - g) <= tol[k] + 1e-6 * abs(g)
        return p == g

    gold_sorted = sorted(gold, key=key)
    perms = itertools.permutations(range(ncol)) if ncol <= 6 else [tuple(range(ncol))]
    for perm in perms:
        cand = sorted((tuple(r[i] for i in perm) for r in pred), key=key)
        if all(all(cell_eq(p[k], g[k], k) for k in range(ncol)) for p, g in zip(cand, gold_sorted)):
            return True
    return False


def pct(n, d):
    return round(100.0 * n / d, 1) if d else None


def summarize(rows):
    n = len(rows)
    lat = [r["latency_s"] for r in rows if r.get("latency_s") is not None]
    tok = [r["tokens"] for r in rows if r.get("tokens")]
    gen = [r["gen_s"] for r in rows if r.get("gen_s")]
    both = [(r["latency_s"], r["tokens"]) for r in rows if r.get("latency_s") is not None and r.get("tokens")]
    tps_pairs = [(r["tokens"], r["gen_s"]) for r in rows if r.get("tokens") and r.get("gen_s")]
    return {
        "questions": n,
        "EX_pct": pct(sum(r["outcome"] == "correct" for r in rows), n),
        "EX_strict_pct": pct(sum(r["strict_correct"] for r in rows), n),
        "VER_pct": pct(sum(r["outcome"] in ("correct", "wrong_result") for r in rows), n),
        "latency_mean_s": round(statistics.mean(lat), 3) if lat else None,
        "latency_median_s": round(statistics.median(lat), 3) if lat else None,
        "latency_p95_s": round(sorted(lat)[max(0, math.ceil(0.95 * len(lat)) - 1)], 3) if lat else None,
        "latency_total_s": round(sum(lat), 1) if lat else None,
        "tokens_mean": round(statistics.mean(tok), 1) if tok else None,
        "tokens_total": sum(tok) if tok else None,
        "ms_per_token": round(1000 * sum(l for l, _ in both) / sum(t for _, t in both), 2) if both else None,
        "tokens_per_s": round(sum(t for t, _ in tps_pairs) / sum(g for _, g in tps_pairs), 2) if tps_pairs else None,
        "sql_exec_ms_mean": round(statistics.mean([r["sql_ms"] for r in rows if r.get("sql_ms") is not None]), 1)
        if any(r.get("sql_ms") is not None for r in rows) else None,
        "outcomes": dict(collections.Counter(r["outcome"] for r in rows)),
    }


def fmt(v, w):
    return f"{'-' if v is None else v:>{w}}"


def print_table(title, groups):
    print(f"\n{title}")
    print(f"  {'':20s}{'n':>5}{'EX%':>7}{'strict%':>9}{'VER%':>7}{'lat s':>8}{'p95 s':>8}{'tok':>7}{'ms/tok':>8}{'tok/s':>8}")
    for name, s in groups:
        print(f"  {name:20s}{fmt(s['questions'], 5)}{fmt(s['EX_pct'], 7)}{fmt(s['EX_strict_pct'], 9)}{fmt(s['VER_pct'], 7)}"
              f"{fmt(s['latency_mean_s'], 8)}{fmt(s['latency_p95_s'], 8)}{fmt(s['tokens_mean'], 7)}"
              f"{fmt(s['ms_per_token'], 8)}{fmt(s['tokens_per_s'], 8)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("predictions")
    ap.add_argument("--variant", choices=["normal", "mixed", "cryptic"], default="normal")
    ap.add_argument("--db"); ap.add_argument("--questions"); ap.add_argument("--stats")
    ap.add_argument("--timeout", type=float, default=30); ap.add_argument("--out")
    ap.add_argument("--only-predicted", action="store_true")
    a = ap.parse_args()
    a.db = a.db or os.path.join(ROOT, "databases", f"cargo_{a.variant}.db")
    a.questions = a.questions or os.path.join(ROOT, "questions", f"questions_{a.variant}.json")
    preds = json.load(open(a.predictions, encoding="utf-8"))
    stats_path = a.stats or (a.predictions[:-5] + "_raw.json" if a.predictions.endswith(".json") else None)
    stats = json.load(open(stats_path, encoding="utf-8")) if stats_path and os.path.exists(stats_path) else {}
    questions = json.load(open(a.questions, encoding="utf-8"))
    if a.only_predicted:
        questions = [q for q in questions if q["id"] in preds]
    print(f"Variant: {a.variant}   database: {os.path.relpath(a.db, ROOT)}   questions: {len(questions)}   "
          f"model stats: {os.path.basename(stats_path) if stats else 'none (latency/token metrics unavailable)'}")
    if stats.get("_run"):
        print("Run: " + ", ".join(f"{k}={v}" for k, v in stats["_run"].items()))

    gold_cache, results = {}, []
    for q in questions:
        key = q.get("base_id", q["id"])
        if key not in gold_cache:
            gold_cache[key] = run(a.db, q["gold_sql"], a.timeout)[1]
        gold = gold_cache[key]
        sql = preds.get(q["id"])
        strict = False
        if not sql:
            outcome, ms = "missing", None
        else:
            st, got, ms = run(a.db, sql, a.timeout)
            if st == "ok":
                outcome = "correct" if same_relaxed(got, gold) else "wrong_result"
                strict = same_strict(got, gold)
            else:
                outcome = "timeout" if st == "timeout" else "execution_error"
        s = stats.get(q["id"], {})
        results.append(dict(id=q["id"], base_id=key, difficulty=q["difficulty"], style=q.get("style"), variant=a.variant,
                            outcome=outcome, strict_correct=strict, sql_ms=ms and round(ms, 1),
                            latency_s=s.get("latency_s"), tokens=s.get("eval_count"), gen_s=s.get("eval_duration_s"),
                            prompt_tokens=s.get("prompt_eval_count")))

    overall = summarize(results)
    by_diff = {d: summarize([r for r in results if r["difficulty"] == d]) for d in DIFFS if any(r["difficulty"] == d for r in results)}
    by_style = {s: summarize([r for r in results if r["style"] == s]) for s in STYLES if any(r["style"] == s for r in results)}
    grid = {d: {s: summarize([r for r in results if r["difficulty"] == d and r["style"] == s])["EX_pct"]
                for s in by_style} for d in by_diff}

    print_table("Overall", [("all", overall)])
    print_table("By difficulty", list(by_diff.items()))
    print_table("By style", list(by_style.items()))
    print("\nEX % by difficulty x style")
    print(f"  {'':10s}" + "".join(f"{s:>20s}" for s in by_style))
    for d, row in grid.items():
        print(f"  {d:10s}" + "".join(fmt(row[s], 20) for s in by_style))
    print("\nOutcomes:", overall["outcomes"])
    print("Prompt tokens per question (mean):",
          round(statistics.mean([r["prompt_tokens"] for r in results if r.get("prompt_tokens")]), 1)
          if any(r.get("prompt_tokens") for r in results) else "-")

    if a.out:
        json.dump({"run": stats.get("_run"), "variant": a.variant, "predictions": os.path.basename(a.predictions),
                   "summary": {"overall": overall, "by_difficulty": by_diff, "by_style": by_style, "ex_grid": grid},
                   "questions": results}, open(a.out, "w", encoding="utf-8"), indent=2)
        print(f"\nResults -> {a.out}")


if __name__ == "__main__":
    main()
